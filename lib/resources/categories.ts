export interface ResourceNode {
  id: string;
  name: string;
  type: 'folder' | 'file';
  children?: ResourceNode[];
  description?: string;
  quickStart?: string;
  status?: 'active' | 'documents' | 'coming_soon';
  toolRoute?: string;
  toolLabel?: string;
  icon?: string;
  color?: string;
  documentId?: string;
  fileName?: string;
  fileType?: string;
  fileSize?: number;
  modelerSummary?: string;
  keyTakeaways?: string[];
  relatedIds?: string[];
}

function file(
  id: string,
  documentId: string,
  fileName: string,
  fileType: string,
  fileSize: number,
  modelerSummary?: string,
  keyTakeaways?: string[],
): ResourceNode {
  return { id, name: fileName, type: 'file', documentId, fileName, fileType, fileSize, modelerSummary, keyTakeaways };
}

