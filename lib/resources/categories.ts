export function flattenTree(node: ResourceNode): ResourceNode[] {
  const result: ResourceNode[] = [node];
  if (node.children) {
    for (const child of node.children) {
      result.push(...flattenTree(child));
    }
  }
  return result;
}

export function findNodeById(id: string, root: ResourceNode = RESOURCE_TREE): ResourceNode | undefined {
  if (root.id === id) return root;
  if (root.children) {
    for (const child of root.children) {
      const found = findNodeById(id, child);
      if (found) return found;
    }
  }
  return undefined;
}

export function getParentPath(targetId: string, root: ResourceNode = RESOURCE_TREE, path: ResourceNode[] = []): ResourceNode[] | null {
  if (root.id === targetId) return path;
  if (root.children) {
    for (const child of root.children) {
      const found = getParentPath(targetId, child, [...path, root]);
      if (found) return found;
    }
  }
  return null;
}

export function searchTree(query: string, root: ResourceNode = RESOURCE_TREE): ResourceNode[] {
  const q = query.toLowerCase();
  return flattenTree(root).filter(
    (n) =>
      n.name.toLowerCase().includes(q) ||
      n.description?.toLowerCase().includes(q) ||
      n.modelerSummary?.toLowerCase().includes(q) ||
      n.keyTakeaways?.some((t) => t.toLowerCase().includes(q))
  );
}

export function countFiles(node: ResourceNode): number {
  if (node.type === 'file') return 1;
  return (node.children || []).reduce((sum, c) => sum + countFiles(c), 0);
}
